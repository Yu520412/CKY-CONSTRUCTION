const menuButton = document.querySelector('.menu-toggle');
const navigation = document.querySelector('.site-nav');
const languageButtons = document.querySelectorAll('[data-lang]');
const supportedLanguages = Object.keys(translations);

function closeMenu() {
  menuButton?.setAttribute('aria-expanded', 'false');
  navigation?.classList.remove('open');
  document.body.classList.remove('menu-open');
}

function setLanguage(language, remember = true) {
  const selectedLanguage = supportedLanguages.includes(language) ? language : 'ms';
  const copy = translations[selectedLanguage];

  document.documentElement.lang = selectedLanguage === 'zh' ? 'zh-CN' : selectedLanguage;
  document.title = copy.metaTitle;
  document.querySelector('meta[name="description"]')?.setAttribute('content', copy.metaDescription);

  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const value = copy[element.dataset.i18n];
    if (value !== undefined) element.textContent = value;
  });
  document.querySelectorAll('[data-i18n-html]').forEach((element) => {
    const value = copy[element.dataset.i18nHtml];
    if (value !== undefined) element.innerHTML = value;
  });
  document.querySelectorAll('[data-i18n-alt]').forEach((element) => {
    const value = copy[element.dataset.i18nAlt];
    if (value !== undefined) element.setAttribute('alt', value);
  });
  document.querySelectorAll('[data-i18n-aria-label]').forEach((element) => {
    const value = copy[element.dataset.i18nAriaLabel];
    if (value !== undefined) element.setAttribute('aria-label', value);
  });
  document.querySelectorAll('[data-wa-link]').forEach((link) => {
    link.setAttribute('href', `https://wa.me/60107768278?text=${encodeURIComponent(copy.waMessage)}`);
  });

  languageButtons.forEach((button) => {
    const isActive = button.dataset.lang === selectedLanguage;
    button.classList.toggle('active', isActive);
    button.setAttribute('aria-pressed', String(isActive));
  });

  if (remember) {
    try { localStorage.setItem('cky-language', selectedLanguage); } catch (_) { /* Storage can be unavailable in private contexts. */ }
  }
}

menuButton?.addEventListener('click', () => {
  const isOpen = menuButton.getAttribute('aria-expanded') === 'true';
  menuButton.setAttribute('aria-expanded', String(!isOpen));
  navigation?.classList.toggle('open', !isOpen);
  document.body.classList.toggle('menu-open', !isOpen);
});

navigation?.querySelectorAll('a').forEach((link) => link.addEventListener('click', closeMenu));
languageButtons.forEach((button) => button.addEventListener('click', () => {
  setLanguage(button.dataset.lang);
  closeMenu();
}));
document.addEventListener('keydown', (event) => { if (event.key === 'Escape') closeMenu(); });

const observer = new IntersectionObserver((entries) => {
  entries.forEach((entry) => {
    if (entry.isIntersecting) {
      entry.target.classList.add('visible');
      observer.unobserve(entry.target);
    }
  });
}, { threshold: 0.12 });

document.querySelectorAll('.reveal').forEach((element) => observer.observe(element));

